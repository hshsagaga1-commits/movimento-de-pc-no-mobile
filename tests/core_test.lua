local path = "rebuild/Core.lua"
assert(loadfile(path), "REBUILD MISSING: production movement core must exist")
local Core = dofile(path)
local count = 0
local function check(name, fn)
    local ok, message = pcall(fn)
    if not ok then error(name .. ": " .. tostring(message), 0) end
    count = count + 1
end
local function eq(actual, expected)
    assert(actual == expected, tostring(actual) .. " ~= " .. tostring(expected))
end
local function obs(extra)
    local value = {alive=true, grounded=true, horizontalSpeed=40, forwardDot=1, canJump=true}
    for k,v in pairs(extra or {}) do value[k] = v end
    return value
end
local function step(engine, x, z, extra, now)
    local result = engine:step({active=true,x=x,z=z},obs(extra),now or 0)
    return Core.chord(result.keys), result
end

check("standing permits only requested PC chords", function()
    local engine = Core.new({})
    eq(step(engine,-1,-1),"W+A")
    eq(step(engine,0,-1),"W")
    eq(step(engine,1,-1),"W+D")
    eq(step(engine,0,1),"S")
    eq(step(engine,-1,0),"W+A")
    eq(step(engine,1,0),"W+D")
    eq(step(engine,-1,1),"S")
    eq(step(engine,0.01,-1),"W")
end)
check("crouch and emote never inject W or S", function()
    for _, state in ipairs({{crouched=true},{emote=true}}) do
        local engine = Core.new({})
        eq(step(engine,-1,-1,state),"A")
        eq(step(engine,1,1,state),"D")
        eq(step(engine,0,-1,state),"-")
        eq(step(engine,0,1,state),"-")
    end
end)
check("airborne standing animation cannot cancel reverse BHOP", function()
    local engine = Core.new({})
    local chord, result = step(engine,-1,-1,{grounded=false,crouched=false,forwardDot=-0.8})
    eq(chord,"A")
    eq(result.flags.REVERSE_BHOP,true)
    eq(result.flags.AIRBORNE,true)
    eq(step(engine,1,-1,{grounded=false,forwardDot=-1},0.001),"D")
end)
check("grounded mode switches apply on same observation", function()
    local engine = Core.new({})
    eq(step(engine,-1,-1),"W+A")
    eq(step(engine,-1,-1,{crouched=true},0.001),"A")
    eq(step(engine,-1,-1,{crouched=false},0.002),"W+A")
end)
check("nearby grid does not restrict standing and real contact does", function()
    local engine = Core.new({})
    eq(step(engine,-1,-1,{gridNearby=true}),"W+A")
    local chord, result = step(engine,-1,-1,{gridContact=true,emote=true})
    eq(chord,"A")
    eq(result.flags.GRID_CONTACT,true)
    eq(result.flags.EMOTE_MOVEMENT,true)
end)
check("neutral and inactive release without delayed latch", function()
    local engine = Core.new({})
    eq(step(engine,1,0),"W+D")
    eq(step(engine,0,0),"-")
    eq(Core.chord(engine:step({active=false,x=1,z=0},obs(),0).keys),"-")
    eq(step(engine,-1,-1,{alive=false}),"-")
    eq(step(engine,1,0,{blocked=true}),"-")
end)
check("intensity thresholds hysteresis and optional A/D swap", function()
    local engine = Core.new({SwapAD=true})
    eq(step(engine,0.1,0),"-")
    eq(step(engine,1,0,{grounded=false}),"A")
    eq(step(engine,-0.25,0,{grounded=false}),"D")
    eq(step(engine,-0.1,0,{grounded=false}),"-")
end)
check("large thumb excursions preserve angle rather than clipping each axis",function()
    local engine=Core.new({})
    eq(step(engine,5,1),"W+D")
    eq(step(engine,1,-5),"W")
end)
check("A to D ledger switch finishes immediately without queued frames", function()
    local events = {}
    local ledger = Core.keys(function(key, down)
        events[#events+1] = key .. (down and "+" or "-")
        return true
    end)
    ledger:apply({A=true})
    ledger:apply({D=true})
    eq(Core.chord(ledger.pressed),"D")
    eq(table.concat(events,","),"A+,D+,A-")
    ledger:apply({D=true})
    eq(#events,3)
    ledger:apply({})
    eq(Core.chord(ledger.pressed),"-")
end)
check("failed key release remains tracked and is retried", function()
    local fail = false
    local events = 0
    local ledger = Core.keys(function(key,down)
        events=events+1
        return not (fail and not down)
    end)
    ledger:apply({A=true})
    fail=true
    ledger:apply({})
    eq(ledger.pressed.A,true)
    fail=false
    ledger:apply({})
    eq(ledger.pressed.A,false)
    eq(events,3)
end)
check("jump sends one native pulse for a tap instead of per-frame spam", function()
    local jump = Core.jump({})
    jump:request(0)
    eq(jump:step(0,obs()),true)
    eq(jump:step(0.01,obs()),true)
    eq(jump.pulses,1)
    eq(jump:step(0.06,obs()),false)
    eq(jump:step(0.2,obs()),false)
    eq(jump.pulses,1)
end)
check("held BHOP requests new native jump on landing only", function()
    local jump = Core.jump({})
    jump:setHeld(true,0)
    jump:step(0,obs())
    jump:step(0.06,obs({grounded=false}))
    jump:step(0.14,obs({grounded=false,gridContact=true}))
    eq(jump.pulses,1)
    local down, reason = jump:step(0.3,obs({gridContact=true}))
    eq(down,true)
    eq(reason,"grid_contact")
    eq(jump.pulses,2)
    jump:step(0.5,obs({gridContact=true}))
    eq(jump.pulses,2)
end)
check("air tap may send Space but grid cannot fabricate an air-jump pulse", function()
    local jump = Core.jump({})
    jump:request(0)
    jump:step(0,obs({grounded=false,gridContact=true}))
    jump:step(0.12,obs({grounded=false,gridContact=true}))
    eq(jump.pulses,1)
    jump:step(0.4,obs({grounded=false,gridNearby=true}))
    eq(jump.pulses,1)
end)
check("expired buffer and disabled jumping never trigger assist", function()
    local jump = Core.jump({})
    jump:request(0)
    eq(jump:step(0,obs({canJump=false,gridContact=true})),false)
    eq(jump:step(0.3,obs({canJump=true,gridContact=true})),false)
    jump:setHeld(true,1)
    eq(jump:step(1,obs({alive=false})),false)
    jump:cancel()
    eq(jump:step(1.2,obs()),false)
end)
check("diagnostics are opt-in and bounded", function()
    local log = Core.log(3)
    log:add({kind="ignored"})
    eq(#log:read(),0)
    log.enabled=true
    for i=1,5 do log:add({i=i}) end
    local entries=log:read()
    eq(#entries,3)
    eq(entries[1].i,3)
    eq(entries[3].i,5)
end)
print("PASS: " .. count .. " core behavior tests")
